"""Local preview server with auto-rebuild and live reload.

Usage: python serve.py [port]   (default port: 8000)

Serves the site at http://localhost:<port>. Whenever build.py or a .bib file
changes, index.html is regenerated by running build.py. Any change to
index.html or assets/ reloads the open browser tab automatically.
Nothing is written to disk except what build.py itself writes.
"""

import http.server
import subprocess
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 8000

# Injected into served HTML pages only (never into the files on disk).
RELOAD_SNIPPET = b"""
<script>
(function () {
  var version = null;
  setInterval(function () {
    fetch('/__livereload', {cache: 'no-store'}).then(function (r) { return r.text(); }).then(function (v) {
      if (version === null) version = v;
      else if (v !== version) location.reload();
    }).catch(function () {});
  }, 1000);
})();
</script>
"""

version = 0


def source_files():
    return [ROOT / 'build.py', *ROOT.glob('*.bib')]


def site_files():
    return [ROOT / 'index.html', *(p for p in (ROOT / 'assets').rglob('*') if p.is_file())]


def snapshot(paths):
    return {p: p.stat().st_mtime for p in paths if p.exists()}


def rebuild():
    print(time.strftime('[%H:%M:%S]'), 'Source changed, rebuilding...')
    result = subprocess.run([sys.executable, 'build.py'], cwd=ROOT, capture_output=True, text=True)
    if result.returncode == 0:
        print('Rebuilt index.html.')
    else:
        print('Build FAILED (index.html left unchanged):')
        print(result.stderr.strip())


def watch():
    global version
    last_src, last_site = snapshot(source_files()), snapshot(site_files())
    while True:
        time.sleep(0.5)
        src = snapshot(source_files())
        if src != last_src:
            time.sleep(0.2)  # let the editor finish writing
            last_src = snapshot(source_files())
            rebuild()
        site = snapshot(site_files())
        if site != last_site:
            last_site = site
            version += 1


class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def end_headers(self):
        self.send_header('Cache-Control', 'no-store')
        super().end_headers()

    def send_bytes(self, body, content_type):
        self.send_response(200)
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if self.path == '/__livereload':
            return self.send_bytes(str(version).encode(), 'text/plain')
        path = Path(self.translate_path(self.path))
        if path.is_dir() and self.path.endswith('/'):
            path = path / 'index.html'
        if path.suffix == '.html' and path.is_file():
            body = path.read_bytes()
            i = body.rfind(b'</body>')
            body = body[:i] + RELOAD_SNIPPET + body[i:] if i != -1 else body + RELOAD_SNIPPET
            return self.send_bytes(body, 'text/html; charset=utf-8')
        super().do_GET()

    def log_message(self, format, *args):
        pass  # keep the terminal for build output


if __name__ == '__main__':
    sys.stdout.reconfigure(line_buffering=True)
    try:
        server = http.server.ThreadingHTTPServer(('127.0.0.1', PORT), Handler)
    except OSError:
        sys.exit(f'Port {PORT} is busy. Try: python serve.py {PORT + 1}')
    threading.Thread(target=watch, daemon=True).start()
    print(f'Previewing at http://localhost:{PORT}  (Ctrl+C to stop)')
    print('Watching build.py and *.bib (rebuild) plus index.html and assets/ (reload).')
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print('\nStopped.')
